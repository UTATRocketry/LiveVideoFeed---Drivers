// ADV 7180 SETUP

#define ADV_ADDRESS 0x42

// store all the required commands for setup
typedef struct {

	  uint8_t reg;
	  uint8_t cmd;

  } ADV_Reg_Config;

uint8_t Write_ADV (uint8_t regAddr, uint8_t data) {

	return HAL_I2C_Mem_Write(&hi2c2, ADV_ADDRESS, regAddr, I2C_MEMADD_SIZE_8BIT, &data, 1, 100);
}

uint8_t Read_ADV (uint8_t regAddr) {

	uint8_t data = 0;
	HAL_I2C_Mem_Read(&hi2c2, ADV_ADDRESS, regAddr, I2C_MEMADD_SIZE_8BIT, &data, 1, 100);
	return data;
}

void ADV_Init (const ADV_Reg_Config config[], uint16_t size) {

	// reset the ADV by writing bit 7 to 1 and wait
	Write_ADV(0x0F, 0x80);
	HAL_Delay(50);

	// iterate through the configure commands
	for (uint16_t i = 0; i < size; i++) {

		uint8_t code = Write_ADV (config[i].reg, config[i].cmd);

		// HAL error code
		if (code != HAL_OK) {
			printf("ERROR WRITING TO ADV7180. CODE 0x%02X\n", code);

			// blink light
			while(1) {
				HAL_GPIO_TogglePin(GPIOA, GPIO_PIN_2);
				HAL_Delay(500);
			}
		}
	}

	uint8_t status = Read_ADV(0x10); // read status 1 from register
	printf("STATUS 1: 0x%0.2X\n", status);

}

